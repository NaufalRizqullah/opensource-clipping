  let language = DEFAULT_LANGUAGE;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'id') language = saved;
  } catch (_) {
    // Browsers may disable storage; switching still works for the current page.
  }

  function t(key, params = {}) {
    const template = messages[language][key] ?? messages.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name) => {
      if (!Object.prototype.hasOwnProperty.call(params, name)) return match;
      const value = params[name];
      return value && typeof value === 'object' && value.key
        ? t(value.key, value.params) : String(value ?? '');
    });
  }

  function text(element, key, params = {}) {
    element.setAttribute('data-i18n', key);
    element.setAttribute('data-i18n-params', JSON.stringify(params));
    element.textContent = t(key, params);
  }

  function literal(element, value) {
    element.removeAttribute('data-i18n');
    element.removeAttribute('data-i18n-params');
    element.textContent = value;
  }

  function escape(value) {
    return String(value).replace(/[&<>"']/g, char => ({
      '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
    }[char]));
  }

  /** Localized template fragments always escape both text and parameters. */
  function html(key, params = {}) {
    return `<span data-i18n="${escape(key)}" data-i18n-params="${escape(JSON.stringify(params))}">${escape(t(key, params))}</span>`;
  }

  function formatDate(value) {
    if (!value) return '—';
    return new Date(value).toLocaleString(language === 'id' ? 'id-ID' : 'en-US', {
      day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit',
    });
  }

  function error(key, params = {}) {
    const result = new Error(t(key, params));
    result.i18nKey = key;
    result.i18nParams = params;
    return result;
  }

  /** Preserve server diagnostics verbatim; only client-owned messages have keys. */
  function errorMessage(value) {
    return value.i18nKey ? { key: value.i18nKey, params: value.i18nParams } : value.message;
  }

  function apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(element => {
      text(element, element.getAttribute('data-i18n'), JSON.parse(element.getAttribute('data-i18n-params') || '{}'));
    });
    for (const attribute of ['placeholder', 'title', 'aria-label', 'content']) {
      root.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
        element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
      });
    }
    root.querySelectorAll('[data-i18n-date]').forEach(element => {
      element.textContent = formatDate(element.getAttribute('data-i18n-date'));
    });
    root.querySelectorAll('[data-language-select]').forEach(select => { select.value = language; });
  }

  function setLanguage(value) {
    language = value === 'id' ? 'id' : DEFAULT_LANGUAGE;
    try { localStorage.setItem(STORAGE_KEY, language); } catch (_) { /* Storage is optional. */ }
    document.documentElement.lang = language;
    apply();
    window.dispatchEvent(new CustomEvent('studio:language', { detail: { language } }));
  }

  document.documentElement.lang = language;
  document.addEventListener('DOMContentLoaded', () => apply());
  return { t, text, literal, html, formatDate, error, errorMessage, apply, setLanguage, getLanguage: () => language };
